"""Konfiguration › KI-Verbindungen: status parsing, set-up commands and texts (no real CLI calls)."""
import ast
import json
import os
import re
import string
import sys
from pathlib import Path
import unittest

SOURCE = Path(__file__).resolve().parents[1] / 'source' / 'workstation.py'
CORE = Path(__file__).resolve().parents[1] / 'source' / 'mpw_core.py'  # Qt-free core (module-level functions)
TEXT = CORE.read_text(encoding='utf-8') + '\n' + SOURCE.read_text(encoding='utf-8')
TREE = ast.parse(TEXT)
NAMES = ('parse_claude_auth_status', 'parse_mcp_get_status', 'tls_interceptor', 'issuer_display_name',
         'claude_desktop_config_snippet', 'mpw_mcp_server_command', 'mcp_setup_command', 'mcp_login_console_command',
         'parse_gemini_mcp_list', 'parse_codex_mcp_list')
CONSTANTS = ('TLS_INTERCEPTION_MARKERS', 'SUNO_MCP_URL', 'MCP_CLIENTS', 'MCP_CLIENT_NAMES')


def load():
    nodes = [n for n in TREE.body
             if (isinstance(n, ast.FunctionDef) and n.name in NAMES)
             or (isinstance(n, ast.Assign) and any(getattr(t, 'id', '') in CONSTANTS for t in n.targets))]
    ns = {'json': json, 're': re, 'sys': sys, 'Path': Path, '__file__': str(SOURCE)}
    exec(compile(ast.Module(body=nodes, type_ignores=[]), str(SOURCE), 'exec'), ns)
    return ns


FN = load()


def class_constant(name):
    cls = next(n for n in TREE.body if isinstance(n, ast.ClassDef) and n.name == 'Workstation')
    node = next(n for n in cls.body if isinstance(n, ast.Assign) and getattr(n.targets[0], 'id', '') == name)
    return ast.literal_eval(node.value)


class StatusParsing(unittest.TestCase):
    def test_claude_auth_status(self):
        parse = FN['parse_claude_auth_status']
        self.assertIs(parse('{\n  "loggedIn": true,\n  "authMethod": "claude.ai"\n}'), True)
        self.assertIs(parse('noise {"loggedIn": false, "authMethod": "none"} more'), False)
        self.assertIsNone(parse('Error: something'))
        self.assertIsNone(parse('{"loggedIn": "yes"}'))

    def test_mcp_get_status_from_real_cli_output(self):
        parse = FN['parse_mcp_get_status']
        self.assertEqual(parse(0, 'suno:\n  Scope: User config\n  Status: √ Connected\n  Type: http'), 'connected')
        self.assertEqual(parse(0, 'mpw:\n  Status: ✓ Connected'), 'connected')
        self.assertEqual(parse(0, 'suno:\n  Status: ! Needs authentication'), 'needs_auth')
        self.assertEqual(parse(0, 'suno:\n  Status: × Failed to connect\n  Issue: InvalidHTTPResponse'), 'failed')
        self.assertEqual(parse(1, 'No MCP server named "mpw". Configured servers: claude.ai Netlify'), 'missing')
        self.assertEqual(parse(1, 'Something else'), 'unknown')

    def test_tls_interceptor(self):
        detect = FN['tls_interceptor']
        norton = 'commonName=Norton Web/Mail Shield Root, organizationName=Norton Web/Mail Shield'
        self.assertEqual(detect(norton), norton)
        self.assertIsNotNone(detect('O=Kaspersky Lab ZAO, CN=Kaspersky Anti-Virus Personal Root'))
        self.assertIsNone(detect('countryName=US, organizationName=Google Trust Services, commonName=WE1'))
        self.assertIsNone(detect("O=Let's Encrypt, CN=R11"))
        self.assertIsNone(detect(''))

    def test_issuer_display_name(self):
        name = FN['issuer_display_name']
        real = ('organizationalUnitName=generated by Norton Antivirus for SSL/TLS scanning, '
                'organizationName=Norton Web/Mail Shield, commonName=Norton Web/Mail Shield Root')
        self.assertEqual(name(real), 'Norton Web/Mail Shield')
        self.assertEqual(name('commonName=Only CN'), 'Only CN')
        self.assertEqual(name(''), '')


class SetupCommands(unittest.TestCase):
    def test_server_command_from_source(self):
        command = FN['mpw_mcp_server_command']()
        self.assertEqual(command[0], sys.executable)
        self.assertTrue(command[1].endswith('mpw_mcp_server.py'))
        self.assertTrue(Path(command[1]).is_file())

    def test_desktop_snippet_is_valid_json_without_write_access(self):
        snippet = json.loads(FN['claude_desktop_config_snippet'](['C:\\MPW\\MPW-MCP.exe']))
        self.assertEqual(snippet, {'mcpServers': {'mpw': {'command': 'C:\\MPW\\MPW-MCP.exe', 'args': []}}})
        self.assertNotIn('allow-write', json.dumps(snippet))

    def test_setup_commands_for_all_three_ais(self):
        cmd = ['C:\\Py\\python.exe', 'C:\\MPW\\mpw_mcp_server.py']
        add = lambda client, server: FN['mcp_setup_command'](client, 'add', server, 'X', cmd)[1:]
        rem = lambda client, server: FN['mcp_setup_command'](client, 'remove', server, 'X')[1:]
        url = 'https://api.suno.com/mcp'
        # Claude Code
        self.assertEqual(add('claude', 'mpw'), ['mcp', 'add', '--scope', 'user', 'mpw', '--', *cmd])
        self.assertEqual(add('claude', 'suno'), ['mcp', 'add', '--scope', 'user', '--transport', 'http', 'suno', url])
        self.assertEqual(rem('claude', 'mpw'), ['mcp', 'remove', 'mpw', '--scope', 'user'])
        # Gemini CLI (docs: gemini mcp add [-s user] [--transport http] <name> <commandOrUrl> [args...])
        self.assertEqual(add('gemini', 'mpw'), ['mcp', 'add', '--scope', 'user', 'mpw', *cmd])
        self.assertEqual(add('gemini', 'suno'), ['mcp', 'add', '--scope', 'user', '--transport', 'http', 'suno', url])
        self.assertEqual(rem('gemini', 'suno'), ['mcp', 'remove', '--scope', 'user', 'suno'])
        # Codex CLI (docs: codex mcp add <name> -- <command>; codex mcp add <name> --url <url>)
        self.assertEqual(add('codex', 'mpw'), ['mcp', 'add', 'mpw', '--', *cmd])
        self.assertEqual(add('codex', 'suno'), ['mcp', 'add', 'suno', '--url', url])
        self.assertEqual(rem('codex', 'mpw'), ['mcp', 'remove', 'mpw'])
        for client in ('claude', 'gemini', 'codex'):
            self.assertNotIn('--allow-write', add(client, 'mpw'))
            self.assertNotIn('--trust', add(client, 'mpw') + add(client, 'suno'))  # never auto-approve tools

    def test_suno_login_per_ai(self):
        login = FN['mcp_login_console_command']
        self.assertEqual(login('claude', 'X'), ['X'])
        self.assertEqual(login('gemini', 'X'), ['X'])
        self.assertEqual(login('codex', 'X'), ['X', 'mcp', 'login', 'suno'])

    def test_gemini_and_codex_lists(self):
        gemini = ('Configured MCP servers:\n\n'
                  '✓ mpw: C:\\Py\\python.exe C:\\MPW\\mpw_mcp_server.py (stdio) - Connected\n'
                  '✗ suno: https://api.suno.com/mcp (http) - Disconnected\n')
        self.assertEqual(FN['parse_gemini_mcp_list'](gemini), {'mpw': 'connected', 'suno': 'registered'})
        self.assertEqual(FN['parse_gemini_mcp_list']('No MCP servers configured.'), {})
        codex = json.dumps([{'name': 'suno', 'transport': {'type': 'streamable_http', 'url': 'https://api.suno.com/mcp'}}])
        self.assertEqual(FN['parse_codex_mcp_list'](codex), {'suno': 'registered'})
        self.assertEqual(FN['parse_codex_mcp_list']('{"mpw": {"command": "x"}}'), {'mpw': 'registered'})
        self.assertEqual(FN['parse_codex_mcp_list']('[]'), {})
        self.assertEqual(FN['parse_codex_mcp_list']('garbage'), {})

    def test_actions_confirm_first_and_use_selected_ai(self):
        self.assertIn("SUNO_MCP_URL = 'https://api.suno.com/mcp'", TEXT)
        for fn in ('ai_connection_add_mpw', 'ai_connection_remove_mpw', 'ai_connection_add_suno', 'ai_connection_remove_suno'):
            start = TEXT.index(f'    def {fn}(self):')
            body = TEXT[start:TEXT.index('\n    def ', start + 10)]
            self.assertIn('_ai_connection_confirm_for(', body, fn)
            self.assertIn('_ai_connection_target(', body, fn)
            self.assertIn('mcp_setup_command(client,', body, fn)

    def test_mpw_prompt_requests_isolated_from_user_mcp_servers(self):
        self.assertIn("args = [executable, '-p', '--output-format', 'text', '--strict-mcp-config']", TEXT)

    def test_checks_never_print_api_keys(self):
        body = TEXT[TEXT.index('def check_ai_connections():'):TEXT.index('class AiConnectionSignals')]
        self.assertIn("bool(os.environ.get(env, '').strip())", body)


class Texts(unittest.TestCase):
    def test_all_languages_have_all_keys_and_placeholders(self):
        texts = class_constant('AI_CONNECTION_TEXTS')
        self.assertEqual(set(texts), {'de', 'en', 'fr', 'es', 'it'})
        fmt = string.Formatter()
        for lang, items in texts.items():
            self.assertEqual(set(items), set(texts['de']), lang)
            for key, value in items.items():
                fields = {f for _, f, _, _ in fmt.parse(value) if f}
                ref = {f for _, f, _, _ in fmt.parse(texts['de'][key]) if f}
                self.assertEqual(fields, ref, f'{lang}.{key}')

    def test_every_widget_key_has_a_text(self):
        texts = class_constant('AI_CONNECTION_TEXTS')['de']
        body = TEXT[TEXT.index('    def _build_ai_connections_dialog(self):'):TEXT.index('    def _retranslate_ai_connections_dialog(self):')]
        used = set(re.findall(r"\('(btn_\w+)'", body)) | set(re.findall(r"group\('(grp_\w+)'", body)) \
            | set(re.findall(r"note='(\w+)'", body)) | set(re.findall(r"key='(\w+)'", body))
        used |= {f'suno_login_started_{c}' for c in ('claude', 'gemini', 'codex')} | {'need_cli', 'mcp_registered',
                                                                                     'confirm_suno_remove', 'target_label'}
        # a text key must not be shared by several widgets (only the last one would get its text)
        keys = re.findall(r"key='(\w+)'", body)
        self.assertEqual(len(keys), len(set(keys)), keys)
        self.assertTrue(used)
        self.assertFalse(used - set(texts), used - set(texts))

    def test_help_entry_translated(self):
        self.assertIn("('KI-Verbindungen', 'KI-Verbindungen einrichten …',", TEXT)
        self.assertIn("'KI-Verbindungen einrichten …': {", TEXT)


if __name__ == '__main__':
    unittest.main()
